#!/usr/bin/env node
/**
 * Concatenates maintained CSS modules into a generated panel.css with no @import.
 * Sources live under web/assets/css/. Run via `npm run build:css`.
 */
const fs = process.getBuiltinModule('fs');
const path = process.getBuiltinModule('path');

const cssDir = path.join(import.meta.dirname, '..', 'web', 'assets', 'css');
const outFile = path.join(import.meta.dirname, '..', 'web', 'generated', 'css', 'panel.css');

/** The order establishes stylesheet cascade priority. */
const MODULES = [
  'tokens.css',
  'layout.css',
  'nav.css',
  'primitives.css',
  'auth.css',
  'inventory.css',
  'manage.css',
  'feedback.css',
  'utilities.css',
  'responsive.css',
];

const BANNER = `/* Generated by scripts/build-css.mjs. Do not edit panel.css directly.
   Edit web/assets/css/*.css modules, then run npm run build:css.
   Entry selectors .auth-page and .panel are defined in the modules below. */
`;

function loadModule(name) {
  const filePath = path.join(cssDir, name);
  if (!fs.existsSync(filePath)) {
    throw new Error(`CSS module missing: ${filePath}`);
  }
  const body = fs.readFileSync(filePath, 'utf8').replace(/\r\n/g, '\n').replace(/\s+$/, '') + '\n';
  return `/* === ${name} === */\n${body}`;
}

const parts = [BANNER];
for (const name of MODULES) {
  parts.push(loadModule(name));
}

const output = `${parts.join('\n')}`;
fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, output, 'utf8');

const rel = path.relative(process.cwd(), outFile);
console.log(`Wrote ${rel} (${Buffer.byteLength(output, 'utf8')} bytes, ${MODULES.length} modules)`);
